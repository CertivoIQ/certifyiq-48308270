import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import test from "node:test";

const root = resolve(new URL("..", import.meta.url).pathname);
const config = JSON.parse(await readFile(resolve(root, "config/final-blocked-source-replacements.json"), "utf8"));

test("replacement inventory is exact, official, and fail-closed", () => {
  assert.equal(config.sourceCount, 6);
  assert.equal(config.sources.length, 6);
  assert.equal(new Set(config.sources.map((source) => source.recordId)).size, 6);
  for (const source of config.sources) {
    assert.match(source.recordId, /^[0-9a-f-]{36}$/);
    assert.ok(source.urls.length >= 1);
    assert.equal(source.discoveryUrl.startsWith("https://"), true);
    for (const candidate of source.urls) {
      const url = new URL(candidate);
      assert.equal(url.protocol, "https:");
      assert.equal(source.allowedHosts.some((host) => url.hostname === host || url.hostname.endsWith(`.${host}`)), true);
    }
  }
});

test("captured manifest has six PDF hashes and no activation authority", async (t) => {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(resolve(root, "artifacts/final-blocked-source-replacements.json"), "utf8"));
  } catch {
    return t.skip("capture artifact is generated by CI");
  }
  assert.equal(manifest.sourceCount, 6);
  assert.equal(manifest.capturedCount, 6);
  assert.equal(manifest.blockedCount, 0);
  assert.equal(manifest.complianceActivationAllowed, false);
  for (const source of manifest.sources) {
    assert.equal(source.captureKind, "controlled_document");
    assert.match(source.sha256, /^[0-9a-f]{64}$/);
    assert.ok(source.byteSize > 0);
    assert.equal(source.complianceActivationAllowed, false);
  }
});
